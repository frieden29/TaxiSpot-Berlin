// Event data is generated by GitHub Actions in web/events.json.
class BerlinEvent {
  final String name;
  final String date;
  final String time;
  final String venue;
  final String url;
  final LatLng location;

  const BerlinEvent({required this.name, required this.date,
    required this.time, required this.venue, required this.url,
    required this.location});

  static BerlinEvent? fromJson(Map<String, dynamic> json) {
    final latitude = num.tryParse(json['latitude'].toString());
    final longitude = num.tryParse(json['longitude'].toString());
    
    if (latitude is! num ||
    longitude is! num ||
    latitude < -90 ||
    latitude > 90 ||
    longitude < -180 ||
    longitude > 180) {
  return null;
}
    final name = json['name'];
    if (name is! String || name.trim().isEmpty) return null;
    return BerlinEvent(
      name: name,
      date: json['date'] is String ? json['date'] as String : '',
      time: json['time'] is String ? json['time'] as String : '',
      venue: json['venue'] is String && (json['venue'] as String).trim().isNotEmpty
          ? json['venue'] as String : 'Veranstaltungsort unbekannt',
      url: json['url'] is String ? json['url'] as String : '',
      location: LatLng(latitude.toDouble(), longitude.toDouble()),
    );
  }
}

