  Future<void> _loadEvents() async {
    try {
      // Relative to the deployed GitHub Pages application directory.
      final uri = Uri.base.resolve('events.json');
      final response = await http.get(uri).timeout(const Duration(seconds: 15));
      if (response.statusCode != 200) {
        throw Exception('Events HTTP ${response.statusCode}');
      }
      final decoded = jsonDecode(response.body) as Map<String, dynamic>;
      final raw = decoded['events'];
      if (raw is! List) throw const FormatException('Invalid events list');
      final events = raw.whereType<Map<String, dynamic>>()
          .map(BerlinEvent.fromJson).whereType<BerlinEvent>().toList();
      debugPrint('EVENTS CHECK: JSON=${raw.length}, VALID=${events.length}');
      if (!mounted) return;
      setState(() {
        _events = events;
        _eventsLoading = false;
        _eventsError = null;
      });
    } catch (error) {
      debugPrint('Events load error: $error');
      if (!mounted) return;
      setState(() {
        _eventsLoading = false;
        _eventsError = 'Veranstaltungen konnten nicht geladen werden';
      });
    }
  }

    List<Marker> _buildEventMarkers() {
  final now = _berlinNow();
  final today = DateTime(now.year, now.month, now.day);

  final filteredEvents = _events.where((event) {
    if (_eventFilter == 'all') {
      return true;
